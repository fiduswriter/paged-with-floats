import express from "express";
import { chromium } from "playwright-core";
const REPO = "/home/johannes/src/paged-test";
const PORT = 9966;
const app = express();
app.use(express.static(REPO));
const server = app.listen(PORT);
const browser = await chromium.launch({ headless: true, args: ["--no-sandbox"] });
const page = await browser.newPage();
const errors = [];
page.on("pageerror", (e) => errors.push(String(e).slice(0, 120)));
await page.goto(`http://localhost:${PORT}/${process.argv[2]}`, { waitUntil: "networkidle" });
await page.waitForFunction(() => document.querySelectorAll(".paged_page").length > 0, { timeout: 30000 }).catch(() => {});
await page.waitForTimeout(1500);
const result = await page.evaluate(async () => {
  const mod = await import("/dist/paged.pdf.js");
  const bytes = await mod.htmlToPDF("<!DOCTYPE html><html><head><style>@page { size: A4; margin: 10mm } p { font-size: 12pt }</style></head><body><p>Hello paged-with-floats PDF export.</p></body></html>", { title: "rename check" });
  const head = Array.from(bytes.slice(0, 5)).map((b) => String.fromCharCode(b)).join("");
  return { bytes: bytes.byteLength, magic: head };
});
console.log(JSON.stringify({ ...result, pageErrors: errors }));
await browser.close();
server.close();
